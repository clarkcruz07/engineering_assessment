import { readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { ROOT } from './database.ts';

/** Publisher exports are the authoritative, independently downloaded record of every published report. */
export const DEFAULT_EXPORTS_DIR = path.join(ROOT, 'data', 'exports');

export interface PublisherReport {
  publisherReportId: string; brandId: string; marketplace: string;
  periodStart: string; periodEnd: string; status: 'partial' | 'complete';
  generatedAt: string; supersededBy: string | null; offerCount: number; activeSubscriptions: number;
}
export interface PublisherOffer { publisherReportId: string; offerId: string; asin: string; activeSubscriptions: number }
export interface PublisherExports {
  reports: PublisherReport[];
  offersByReport: Map<string, PublisherOffer[]>;
  files: { name: string; sha256: string }[];
}

const REPORT_COLUMNS = ['publisher_report_id', 'brand_id', 'marketplace', 'period_start', 'period_end', 'status', 'generated_at', 'superseded_by', 'offer_count', 'active_subscriptions'];
const OFFER_COLUMNS = ['publisher_report_id', 'offer_id', 'asin', 'active_subscriptions'];

function parseCsv(text: string, file: string, required: string[]): Record<string, string>[] {
  const [header, ...lines] = text.replace(/^﻿/, '').trim().split(/\r?\n/);
  const keys = header.split(',').map(k => k.trim());
  const missing = required.filter(c => !keys.includes(c));
  if (missing.length) throw new Error(`${file} is missing columns: ${missing.join(', ')}`);
  return lines.filter(l => l.trim()).map((line, i) => {
    if (line.includes('"')) throw new Error(`${file} line ${i + 2}: quoted CSV values are not supported`);
    const values = line.split(',');
    if (values.length !== keys.length) throw new Error(`${file} line ${i + 2}: expected ${keys.length} values, found ${values.length}`);
    return Object.fromEntries(values.map((v, j) => [keys[j], v.trim()]));
  });
}

function count(value: string, where: string): number {
  const n = Number(value);
  if (!Number.isInteger(n) || n < 0) throw new Error(`${where}: invalid nonnegative count "${value}"`);
  return n;
}

export async function loadPublisherExports(dir = DEFAULT_EXPORTS_DIR): Promise<PublisherExports> {
  const reportText = await readFile(path.join(dir, 'subscription_reports.csv'), 'utf8');
  const offerText = await readFile(path.join(dir, 'subscription_offers.csv'), 'utf8');
  const reports = parseCsv(reportText, 'subscription_reports.csv', REPORT_COLUMNS).map(r => {
    if (r.status !== 'partial' && r.status !== 'complete') throw new Error(`subscription_reports.csv: unknown status "${r.status}"`);
    return {
      publisherReportId: r.publisher_report_id, brandId: r.brand_id, marketplace: r.marketplace,
      periodStart: r.period_start, periodEnd: r.period_end, status: r.status,
      generatedAt: new Date(r.generated_at).toISOString(), supersededBy: r.superseded_by || null,
      offerCount: count(r.offer_count, r.publisher_report_id), activeSubscriptions: count(r.active_subscriptions, r.publisher_report_id),
    } satisfies PublisherReport;
  });
  const offersByReport = new Map<string, PublisherOffer[]>();
  for (const o of parseCsv(offerText, 'subscription_offers.csv', OFFER_COLUMNS)) {
    const offer = { publisherReportId: o.publisher_report_id, offerId: o.offer_id, asin: o.asin, activeSubscriptions: count(o.active_subscriptions, o.offer_id) };
    const list = offersByReport.get(offer.publisherReportId);
    if (list) list.push(offer); else offersByReport.set(offer.publisherReportId, [offer]);
  }
  const sha = (t: string) => createHash('sha256').update(t).digest('hex');
  return { reports, offersByReport, files: [{ name: 'subscription_reports.csv', sha256: sha(reportText) }, { name: 'subscription_offers.csv', sha256: sha(offerText) }] };
}

/**
 * Selects the publisher's report for one scope and week as known at `asOf`:
 * only reports generated by then; drop reports superseded by another available report;
 * then complete over partial, greatest period_end, latest generation time.
 */
export function selectPublisherReport(reports: PublisherReport[], brandId: string, marketplace: string, periodStart: string, asOf: string) {
  const cutoff = Date.parse(asOf);
  const available = reports.filter(r => r.brandId === brandId && r.marketplace === marketplace
    && r.periodStart === periodStart && Date.parse(r.generatedAt) <= cutoff);
  const availableIds = new Set(available.map(r => r.publisherReportId));
  const current = available.filter(r => !(r.supersededBy && availableIds.has(r.supersededBy)));
  const ranked = [...current].sort((a, b) =>
    (a.status === 'complete' ? 0 : 1) - (b.status === 'complete' ? 0 : 1)
    || b.periodEnd.localeCompare(a.periodEnd)
    || Date.parse(b.generatedAt) - Date.parse(a.generatedAt));
  return { selected: ranked[0] ?? null, available: available.sort((a, b) => Date.parse(a.generatedAt) - Date.parse(b.generatedAt)) };
}
